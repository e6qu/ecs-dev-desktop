// Boot-time installer for the session owner's platform-generated git SSH keys.
//
// Fetches the keys from the control plane over the idle-agent's authenticated channel and
// writes them to tmpfs-like container-local storage (/run/edd/ssh — never the persisted
// /data volume, so a snapshot never carries a private key), plus an ssh_config for the git
// host and its published host keys. The workspace user's ~/.ssh/config gains a single
// `Include` line so both the bootstrap clone and anything the user runs from the terminal
// use the keys without further setup. Runs as root from the entrypoint on EVERY boot (a
// woken workspace is a fresh container), so keys added or removed in the portal apply on
// the next start. Exit code is always 0: the workspace still starts without keys, but the
// reason is printed to stderr (→ the boot log) rather than silently swallowed.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const RUNTIME_PARENT = "/run/edd";
const RUNTIME_DIR = `${RUNTIME_PARENT}/ssh`;
const HOME = "/data/home";
const USER = "workspace";
const INCLUDE_LINE = `Include ${RUNTIME_DIR}/config`;
const FETCH_TIMEOUT_MS = 10_000;

function log(message) {
  process.stderr.write(`edd-git-ssh: ${message}\n`);
}

function chownToWorkspace(path) {
  execFileSync("chown", [`${USER}:${USER}`, path]);
}

async function fetchKeys() {
  const url = `${process.env.EDD_CONTROL_PLANE_URL}/api/workspaces/${process.env.EDD_WORKSPACE_ID}/git-ssh-keys`;
  const res = await fetch(url, {
    headers: { Authorization: `Bearer ${process.env.EDD_AGENT_TOKEN}` },
    signal: AbortSignal.timeout(FETCH_TIMEOUT_MS),
  });
  if (res.status === 204) return null;
  if (!res.ok) throw new Error(`the control plane answered HTTP ${res.status}`);
  const body = await res.json();
  if (
    typeof body.host !== "string" ||
    !Array.isArray(body.keys) ||
    !Array.isArray(body.knownHosts)
  ) {
    throw new Error("the control plane answered with an unexpected body");
  }
  return body;
}

/** Write the runtime directory: one file per key, known_hosts, and the ssh_config block. */
function install(bundle) {
  // The parent (/run/edd) is root-owned and world-traversable; only the key directory
  // itself is private to the workspace user. ssh silently skips an `Include` it cannot
  // read, so a root-only parent would make every key vanish without a word.
  mkdirSync(RUNTIME_PARENT, { recursive: true, mode: 0o755 });
  mkdirSync(RUNTIME_DIR, { recursive: true, mode: 0o700 });
  chownToWorkspace(RUNTIME_DIR);
  const identityFiles = [];
  for (const key of bundle.keys) {
    const file = join(RUNTIME_DIR, key.id);
    writeFileSync(file, key.privateKey.endsWith("\n") ? key.privateKey : `${key.privateKey}\n`, {
      mode: 0o600,
    });
    chownToWorkspace(file);
    writeFileSync(`${file}.pub`, `${key.publicKey}\n`, { mode: 0o644 });
    chownToWorkspace(`${file}.pub`);
    identityFiles.push(file);
  }
  const pinned = bundle.knownHosts.length > 0;
  const knownHostsFile = join(RUNTIME_DIR, "known_hosts");
  writeFileSync(knownHostsFile, bundle.knownHosts.map((line) => `${line}\n`).join(""), {
    mode: 0o644,
  });
  chownToWorkspace(knownHostsFile);
  const config = [
    `# Generated by edd-git-ssh at boot; edit ~/.ssh/config, not this file.`,
    `Host ${bundle.host}`,
    ...identityFiles.map((file) => `  IdentityFile ${file}`),
    `  IdentitiesOnly yes`,
    `  BatchMode yes`,
    // With published host keys the host must match them; without, the first connection
    // records the key it sees (and the boot log says so below).
    `  UserKnownHostsFile ${knownHostsFile}`,
    `  StrictHostKeyChecking ${pinned ? "yes" : "accept-new"}`,
    "",
  ].join("\n");
  const configFile = join(RUNTIME_DIR, "config");
  writeFileSync(configFile, config, { mode: 0o644 });
  chownToWorkspace(configFile);
  return { count: identityFiles.length, pinned };
}

/** Make sure ~/.ssh/config starts with the Include (idempotent; keeps the user's own config). */
function ensureInclude() {
  const sshDir = join(HOME, ".ssh");
  mkdirSync(sshDir, { recursive: true, mode: 0o700 });
  chownToWorkspace(sshDir);
  const configFile = join(sshDir, "config");
  const existing = existsSync(configFile) ? readFileSync(configFile, "utf8") : "";
  if (existing.split("\n").some((line) => line.trim() === INCLUDE_LINE)) return;
  writeFileSync(configFile, `${INCLUDE_LINE}\n${existing}`, { mode: 0o600 });
  chownToWorkspace(configFile);
}

try {
  for (const name of ["EDD_CONTROL_PLANE_URL", "EDD_WORKSPACE_ID", "EDD_AGENT_TOKEN"]) {
    if (!process.env[name]) throw new Error(`${name} is not set`);
  }
  const bundle = await fetchKeys();
  if (bundle === null) {
    log("no GitHub SSH keys for this session's owner (generate one under Settings → SSH keys)");
  } else {
    const { count, pinned } = install(bundle);
    ensureInclude();
    log(
      `installed ${count} GitHub SSH key(s) for ${bundle.host}` +
        (pinned
          ? " with its published host keys"
          : "; the host publishes no host keys, so the first connection's key is trusted"),
    );
  }
} catch (error) {
  log(
    `could not install GitHub SSH keys: ${error instanceof Error ? error.message : String(error)}`,
  );
}
